def process(path, repls, is_txt):
    s = io.open(path, encoding='utf-8-sig').read()
    orig = s
    cnt = 0
    for old, new in repls:
        if old in s:
            s = s.replace(old, new)
            cnt += 1
    if s != orig:
        enc = 'utf-8-sig' if is_txt else 'utf-8'
        io.open(path, 'w', encoding=enc, newline='').write(s)
    return cnt

