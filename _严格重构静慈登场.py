def process(path, is_txt):
    s = io.open(path, encoding='utf-8-sig').read()
    orig = s
    ok = 0
    fail = []
    for i, (old, new) in enumerate(repls):
        if old in s:
            s = s.replace(old, new)
            ok += 1
        else:
            fail.append(i)
    if s != orig:
        enc = 'utf-8-sig' if is_txt else 'utf-8'
        io.open(path, 'w', encoding=enc, newline='').write(s)
    return ok, fail

